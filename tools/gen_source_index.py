#!/usr/bin/env python3
"""Generate docs/SOURCE_INDEX.md: one row per source file with its purpose and original addresses.

Purpose = the first comment block of the file (the repository convention is to open each
recovered file with a comment naming the routine and its 0x address). Addresses = every
distinct `0x4xxxxx`..`0x8xxxxx` literal in the file, split into code (<0x7a0000 heuristic is
not used; all are listed, truncated) so readers can jump to the evidence.

Usage: gen_source_index.py [--out docs/SOURCE_INDEX.md]
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDR = re.compile(r'(?<![0-9A-Za-z_])0[xX]([4-8][0-9a-fA-F]{5})(?![0-9A-Za-z_])')
EXT = ('.cpp', '.h', '.inc', '.c')


def purpose(text):
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines) and (not lines[i].strip() or lines[i].startswith('#')):
        i += 1
    if i < len(lines) and lines[i].lstrip().startswith('/*'):
        while i < len(lines):
            out.append(lines[i].strip().lstrip('/*').rstrip('*/').strip())
            if '*/' in lines[i]:
                break
            i += 1
    else:
        # skip leading #include lines, then take the first // block
        j = 0
        while j < len(lines):
            s = lines[j].strip()
            if s.startswith('//'):
                while j < len(lines) and lines[j].strip().startswith('//'):
                    out.append(lines[j].strip()[2:].strip())
                    j += 1
                break
            if s and not s.startswith('#'):
                break
            j += 1
    p = ' '.join(x for x in out if x)
    if not p:
        names = []
        for ln in lines:
            m = re.match(r'^(?:[A-Za-z_][\w:<>\*&]*[\s\*&]+)+((?:[A-Za-z_]\w*::)?[A-Za-z_~]\w*)\s*\([^;]*$', ln)
            if m and m.group(1) not in ('if', 'for', 'while', 'switch', 'return') and m.group(1) not in names:
                names.append(m.group(1))
        if names:
            p = 'Defines: ' + ', '.join(f'`{n}`' for n in names[:5]) + (' ...' if len(names) > 5 else '')
    return (p[:220] + '...') if len(p) > 220 else p


def section(title, base, w, recursive=True):
    files = sorted(f for f in (base.rglob('*') if recursive else base.glob('*'))
                   if f.is_file() and f.suffix in EXT and 'Recovered' not in f.parts)
    if not files:
        return
    w(f'\n## {title}\n')
    w('| File | Purpose (first comment) | Addresses |\n| --- | --- | --- |')
    for f in files:
        t = f.read_text(errors='replace')
        addrs = sorted({int(m.group(1), 16) for m in ADDR.finditer(t)})
        shown = ' '.join(f'`{a:06x}`' for a in addrs[:6]) + (f' +{len(addrs)-6}' if len(addrs) > 6 else '')
        pur = purpose(t).replace('|', '\\|')
        w(f'| `{f.relative_to(ROOT)}` | {pur} | {shown} |')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT / 'docs' / 'SOURCE_INDEX.md'))
    a = ap.parse_args()
    out = []
    w = out.append
    w('# Source index\n')
    w('Generated by `tools/gen_source_index.py`; do not edit by hand. Purposes are the first '
      'comment of each file; addresses are original UG2 PC v1.2 virtual addresses cited in the '
      'file (hex, first six). See `docs/ARCHITECTURE.md` for how the pieces fit together.')
    sd = ROOT / 'src' / 'Speed' / 'Indep'
    for title, sub in (('Physics', 'Src/Physics'), ('World', 'Src/World'), ('Camera', 'Src/Camera'),
                       ('HUD', 'Src/Hud'), ('Frontend (FEng, menus)', 'Src/Frontend'),
                       ('Gameplay', 'Src/Gameplay'), ('Audio', 'Src/Audio'),
                       ('EAXSound / Ginsu', 'Src/EAXSound'), ('bWare library', 'Libs/bWare'),
                       ('D3DX / effect framework', 'Libs/D3DX')):
        section(title, sd / sub, w)
    rec = ROOT / 'src/Speed/Indep/Recovered'
    if rec.exists():
        nb = sum(1 for f in rec.rglob('*.c') if 'Behavior' not in f.parts)
        nh = sum(1 for f in (rec / 'Behavior').rglob('*.c')) if (rec / 'Behavior').exists() else 0
        w('\n## Auto-matched recovery (not listed per file)\n')
        w('`src/Speed/Indep/Recovered/<0xNN>/FUN_<addr>.c`: %d byte-identical functions (manifest '
          '`config/SPEED2_EXE_1_2/auto-matched.json`).  \n`src/Speed/Indep/Recovered/Behavior/...`: %d behaviour-verified '
          'functions (manifest `behavior-matched.json`). See `docs/AUTO_MATCH.md`.' % (nb, nh))
    section('Platform: native Linux scaffolding', ROOT / 'src' / 'Platform' / 'Native', w, recursive=False)
    section('Modding SDK and runtime', ROOT / 'modding', w)
    w('\n## Tools\n')
    w('| Script | Purpose |\n| --- | --- |')
    for f in sorted((ROOT / 'tools').glob('*.py')):
        t = f.read_text(errors='replace')
        m = re.match(r'(?:#![^\n]*\n)?\s*(?:"""|\'\'\')(.*?)(?:"""|\'\'\')', t, re.S)
        d = ' '.join(m.group(1).strip().split('\n\n')[0].split()) if m else ''
        w(f'| `tools/{f.name}` | {d[:200].replace("|", chr(92)+"|")} |')
    Path(a.out).write_text('\n'.join(out) + '\n')
    print(f'{len(out)} lines -> {a.out}')


if __name__ == '__main__':
    main()
